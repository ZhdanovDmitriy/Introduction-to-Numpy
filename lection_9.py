# Машинное обучение можно разделить на два подраздела:
# Обучение с учителем(supervised learning)
# Обучение без учителя(unsupervised learning)


###Обучение с учителем(supervised learning)
# Моделирует отношение между признаками и метками(результатом)
# Такие модели служат для предсказания меток на основе обучающих данных маркированных.
# После построения модели можно использовать её для присвоения новых меток ранее неизвестным данным
# Подзадачи:
# Классификация(метки - дискретные, два или более)
# Регресия(метки - непрерывные величины(действительные числа))


###Обучение без учителя(нет меток)
# Служат для выявления структуры немаркированных данных
# Подзадачи:
# Кластеризация(выделяет отдельные группы данных)
# Уменьшение размерности(поиск более сжатого представления данных)


###Существуют методы частичного обучения(semi-supervised learning)
# Метки неполные(не все данные маркерованы)


###Методы обучения с подкреплением(reinforcement learning)
